import test from 'node:test';
import assert from 'node:assert/strict';
import { localCommand, parseRecords } from '../server/adapters/normalize.js';
import { localizeSession } from '../src/shared/canonical.js';
import { noticeCandidates } from '../src/shared/notices.js';
import type { Session } from '../src/shared/types.js';

// Record shapes follow Claude Code 2.1.322's own writers (synthetic text, no real transcript):
// a local command is a user record that starts with `<command-name>`, its output a user record
// (older) or a `system`/`local_command` record (newer) with `<local-command-stdout>`, and the
// caveat before it is `isMeta`. A command that expands into a prompt starts with
// `<command-message>` and is followed by the expanded prompt as an `isMeta` user record.
const now = Date.parse('2026-11-10T00:00:00Z');
const at = (n: number) => new Date(now - 60_000 + n * 1000).toISOString();
const base = { sessionId: 'local-1', cwd: '/tmp/project' };
const claude = {
  provider: 'claude' as const,
  sourcePath: '/test/local-1.jsonl',
  mtime: now - 60_000,
  now,
};
const user = (uuid: string, n: number, content: unknown, extra: object = {}) => ({
  ...base,
  type: 'user',
  uuid,
  timestamp: at(n),
  message: { role: 'user', content },
  ...extra,
});
const reply = (uuid: string, n: number, text: string) => ({
  ...base,
  type: 'assistant',
  uuid,
  timestamp: at(n),
  message: {
    id: `m-${uuid}`,
    role: 'assistant',
    stop_reason: 'end_turn',
    content: [{ type: 'text', text }],
  },
});
const caveat = (uuid: string, n: number) =>
  user(
    uuid,
    n,
    '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>',
    { isMeta: true },
  );
const command = (uuid: string, n: number, name: string, args = '') =>
  user(
    uuid,
    n,
    `<command-name>/${name}</command-name>\n            <command-message>${name}</command-message>\n            <command-args>${args}</command-args>`,
  );
const stdout = (uuid: string, n: number, text: string) =>
  user(uuid, n, `<local-command-stdout>${text}</local-command-stdout>`);
const systemOutput = (uuid: string, n: number, text: string) => ({
  ...base,
  type: 'system',
  subtype: 'local_command',
  uuid,
  timestamp: at(n),
  level: 'info',
  isMeta: false,
  content: `<local-command-stdout>${text}</local-command-stdout>`,
});
const answered = [user('u1', 0, 'Fix the flaky test'), reply('a1', 1, 'Fixed it.')];
const requests = (s: Session) => s.events.filter((e) => e.kind === 'user');
const lines = (s: Session) => s.events.filter((e) => e.kind === 'lifecycle').map((e) => e.text);

test('localCommand tells local commands and their output from prompts', () => {
  assert.deepEqual(
    localCommand('<command-name>/usage</command-name>\n<command-args></command-args>'),
    {
      line: '/usage',
    },
  );
  assert.deepEqual(
    localCommand('<command-name>/model</command-name><command-args>opus</command-args>'),
    { line: '/model opus' },
  );
  assert.deepEqual(localCommand('<bash-input>git status</bash-input>'), { line: '!git status' });
  for (const output of [
    '<local-command-stdout>Total cost: $0.12</local-command-stdout>',
    '<local-command-stderr>Unknown command</local-command-stderr>',
    '<local-command-caveat>Caveat</local-command-caveat>',
    '<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>',
  ])
    assert.deepEqual(localCommand(output), {});
  // A custom command or skill expands into a prompt: not local.
  assert.equal(
    localCommand(
      '<command-message>review is running…</command-message>\n<command-name>/review</command-name>',
    ),
    undefined,
  );
  assert.equal(localCommand('Please run /usage for me'), undefined);
});

test('/usage after an answered turn does not open a request: status stays as it was', () => {
  const before = parseRecords(answered, claude);
  assert.equal(before.observedStatus, 'done');
  // Older Claude Code: caveat (meta), command, output, all user records.
  const older = parseRecords(
    [...answered, caveat('c1', 30), command('u2', 30, 'usage'), stdout('o1', 30, 'Session: 12%')],
    claude,
  );
  // Claude Code 2.1.322: the command as a user record, its output as a system record.
  const newer = parseRecords(
    [...answered, command('u2', 30, 'usage'), systemOutput('o1', 30, 'Session: 12%')],
    claude,
  );
  for (const s of [older, newer]) {
    assert.equal(s.observedStatus, 'done');
    assert.equal(s.status, before.status);
    assert.equal(s.statusReason, before.statusReason);
    assert.equal(s.runtime?.phase, 'responded');
    // Not a request: no new turn, no request notice, the activity still quotes the reply.
    assert.deepEqual(
      requests(s).map((e) => e.text),
      ['Fix the flaky test'],
    );
    assert.equal(s.taskStartedAt, before.taskStartedAt);
    assert.equal(s.activity?.text, 'Fixed it.');
    assert.equal(s.updatedAt, before.updatedAt);
    assert.ok(!noticeCandidates(s, now).some((n) => n.kind === 'request' && /usage/.test(n.text)));
    // A small system line instead of the markup; the output and caveat are not shown.
    assert.deepEqual(lines(s), ['/usage 실행']);
    assert.ok(!s.events.some((e) => /local-command|command-name|Session: 12%/.test(e.text)));
  }
  assert.notEqual(older.revision, before.revision);
});

test('/cost and /model keep a resting colleague resting; the line is localized on read', () => {
  const resting = { ...claude, now: now + 3 * 3600_000 };
  const before = parseRecords(answered, resting);
  assert.equal(before.status, 'idle');
  const s = parseRecords(
    [
      ...answered,
      caveat('c1', 3 * 3600),
      command('u2', 3 * 3600, 'cost'),
      stdout('o1', 3 * 3600, 'Total cost: $0.12'),
      command('u3', 3 * 3600 + 5, 'model', 'sonnet'),
      systemOutput('o2', 3 * 3600 + 5, 'Set model to sonnet'),
    ],
    resting,
  );
  assert.equal(s.status, 'idle');
  assert.equal(s.observedStatus, 'done');
  assert.equal(requests(s).length, 1);
  assert.deepEqual(lines(s), ['/cost 실행', '/model sonnet 실행']);
  assert.deepEqual(lines(localizeSession(s, 'en')), ['Ran /cost', 'Ran /model sonnet']);
});

test('A session that only ran a local command waits for nothing and keeps no command title', () => {
  const s = parseRecords(
    [caveat('c1', 0), command('u1', 0, 'status'), systemOutput('o1', 0, 'Version: 2.1.322')],
    claude,
  );
  assert.equal(s.observedStatus, 'idle');
  assert.equal(requests(s).length, 0);
  assert.doesNotMatch(s.title, /command-name|status/);
  // A command shown as a system record (a dialog command) gets the same line.
  const dialog = parseRecords(
    [
      {
        ...base,
        type: 'system',
        subtype: 'local_command',
        uuid: 's1',
        timestamp: at(0),
        content:
          '<command-name>/config</command-name>\n<command-message>config</command-message>\n<command-args></command-args>',
      },
      systemOutput('o1', 0, 'Config dialog dismissed'),
    ],
    claude,
  );
  assert.equal(dialog.observedStatus, 'idle');
  assert.deepEqual(lines(dialog), ['/config 실행']);
});

test('A prompt typed after a local command still opens a request', () => {
  const s = parseRecords(
    [
      ...answered,
      command('u2', 30, 'usage'),
      systemOutput('o1', 30, 'Session: 12%'),
      user('u3', 40, 'Now update the docs'),
    ],
    claude,
  );
  assert.equal(s.observedStatus, 'think');
  assert.equal(s.status, 'think');
  assert.equal(requests(s).at(-1)?.text, 'Now update the docs');
  assert.equal(s.activity?.text, 'Now update the docs');
  assert.equal(s.taskStartedAt, Date.parse(at(40)));
});

test('A local command run while a turn is still going does not end or restart it', () => {
  const s = parseRecords(
    [user('u1', 0, 'Refactor the parser'), command('u2', 5, 'usage'), systemOutput('o1', 5, '12%')],
    claude,
  );
  assert.equal(s.observedStatus, 'think');
  assert.equal(s.taskStartedAt, Date.parse(at(0)));
  assert.equal(s.activity?.text, 'Refactor the parser');
});

test('A custom command or skill that expands into a prompt is a request for the model', () => {
  const invoked = user(
    'u2',
    30,
    '<command-message>review is running…</command-message>\n<command-name>/review</command-name>\n<command-args>#12</command-args>',
  );
  const expanded = user('u3', 30, [{ type: 'text', text: 'Review pull request #12 …' }], {
    isMeta: true,
  });
  const s = parseRecords([...answered, invoked, expanded], claude);
  assert.equal(s.observedStatus, 'think');
  assert.equal(requests(s).length, 2);
  assert.equal(lines(s).length, 0);
  const done = parseRecords(
    [...answered, invoked, expanded, reply('a2', 40, 'Looks good.')],
    claude,
  );
  assert.equal(done.observedStatus, 'done');
  assert.equal(done.activity?.text, 'Looks good.');
});

test('/compact records its finished work as a local command, and the summary is no request', () => {
  const s = parseRecords(
    [
      ...answered,
      {
        ...base,
        type: 'system',
        subtype: 'compact_boundary',
        uuid: 'b1',
        timestamp: at(30),
        content: 'Conversation compacted',
      },
      user(
        'u2',
        30,
        'This session is being continued from a previous conversation that ran out of context.',
        { isCompactSummary: true, isVisibleInTranscriptOnly: true },
      ),
      caveat('c1', 31),
      command('u3', 31, 'compact'),
      stdout('o1', 31, 'Compacted (ctrl+o to see full summary)'),
    ],
    claude,
  );
  assert.equal(s.observedStatus, 'done');
  assert.equal(requests(s).length, 1);
  assert.deepEqual(lines(s), ['/compact 실행']);
  assert.doesNotMatch(s.title, /continued from a previous conversation/);
  // Work after compaction (an automatic one mid-turn) is still seen from the replies.
  const after = parseRecords(
    [
      user('u1', 0, 'Keep going'),
      user('u2', 10, 'This session is being continued …', { isCompactSummary: true }),
      reply('a1', 20, 'Continuing.'),
    ],
    claude,
  );
  assert.equal(after.observedStatus, 'done');
  assert.equal(requests(after).length, 1);
});

test('A ! shell command is local too', () => {
  const s = parseRecords(
    [
      ...answered,
      user('u2', 30, '<bash-input>git status</bash-input>'),
      user('u3', 30, '<bash-stdout>clean</bash-stdout><bash-stderr></bash-stderr>'),
    ],
    claude,
  );
  assert.equal(s.observedStatus, 'done');
  assert.equal(requests(s).length, 1);
  assert.deepEqual(lines(s), ['!git status 실행']);
});

test('a long local command is redacted before it is clipped, so no secret leaks past the cut', () => {
  const secret = 'sk-' + 'a'.repeat(48);
  const line = localCommand(
    `<bash-input>curl -H "Authorization: Bearer ${'x'.repeat(90)}" ${secret}</bash-input>`,
  )!.line!;
  assert.ok(!line.includes('sk-aaaa'), line);
  assert.ok(line.length <= 120);
});
